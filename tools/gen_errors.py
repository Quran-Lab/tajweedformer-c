"""Generates src/tf/tf_error_catalogue.h from the error catalogue shared by the four SDKs.

  python tools/gen_errors.py [path/to/errors.json]

The catalogue is one JSON file shared by the SDKs (sdk_3.0.0/errors.json): for each error its stable `code`, its
`message` (with {placeholders} the SDK fills), a `fix` a developer can act on, and the docs link docs_base + code.
The SDK embeds the file as it is (the bytes, so a test can compare them with the shared file and with a recorded
SHA-256) and, generated from the same bytes, a C table of the entries in the file's order and a second table of
the `reasons` of server_rejected (one message and one fix per refusal the server names). The order is the
order of the TfError values in include/tajweedformer.h (the first entry is -1, the second -2, ...); the errors
test fails when they differ.

Without an argument the repository's copy is read (test/data/sdk_3.0.0/errors.json, which the errors test
compares with the embedded bytes). Run it again whenever the catalogue changes; never edit the generated header
by hand.

Tried and rejected: parsing the JSON at run time (the library would carry a parser path for text it compiles in);
typing the table by hand (it drifted from the catalogue once in another SDK).
"""
import hashlib
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
DEFAULT = root / "test" / "data" / "sdk_3.0.0" / "errors.json"
src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
raw = src.read_bytes()
cat = json.loads(raw.decode("utf-8"))
if cat.get("format") != "quranlab.sdk-errors/1":
    sys.exit(f"{src}: not a quranlab.sdk-errors/1 catalogue")


def c_string(s):
    """A C string literal for UTF-8 text (the catalogue is ASCII; anything else is written as octal bytes)."""
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(ch)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


lines = [
    "/* Generated by tools/gen_errors.py from the shared catalogue, sdk_3.0.0/errors.json. Do not edit: run the tool again. */",
    "#ifndef TF_ERROR_CATALOGUE_H",
    "#define TF_ERROR_CATALOGUE_H",
    "",
    f"#define TF_ERRORS_SDK {c_string(cat['sdk'])}",
    f"#define TF_ERRORS_DOCS_BASE {c_string(cat['docs_base'])}",
    f"#define TF_ERRORS_COUNT {len(cat['errors'])}",
    f"#define TF_ERRORS_JSON_SIZE {len(raw)}",
    f"#define TF_ERRORS_JSON_SHA256 \"{hashlib.sha256(raw).hexdigest()}\"",
    "",
    "typedef struct {",
    "  const char *code, *message, *fix;",
    "} TfErrorEntry;",
    "",
    "/* the entries in the catalogue's order: entry i is the TfError value -(i + 1) */",
    "static const TfErrorEntry kTfErrors[TF_ERRORS_COUNT] = {",
]
for e in cat["errors"]:
    lines.append(f"    {{{c_string(e['code'])},\n     {c_string(e['message'])},\n     {c_string(e['fix'])}}},")
# the refusals of server_rejected: the server's 403 code, and the message and fix that say what to do about it
reasons = next(e for e in cat["errors"] if e["code"] == "server_rejected").get("reasons", {})
lines += ["};", "", f"#define TF_REASONS_COUNT {len(reasons)}", "",
          "/* server_rejected by the server's code: the message and the fix of that refusal */",
          "static const TfErrorEntry kTfReasons[TF_REASONS_COUNT] = {"]
for code, r in reasons.items():
    lines.append(f"    {{{c_string(code)},\n     {c_string(r['message'])},\n     {c_string(r['fix'])}}},")
lines += ["};", "", "/* the catalogue file, byte for byte */", "static const unsigned char kTfErrorsJson[TF_ERRORS_JSON_SIZE] = {"]
for at in range(0, len(raw), 24):
    lines.append("    " + ",".join(str(b) for b in raw[at:at + 24]) + ",")
lines += ["};", "", "#endif", ""]
out = root / "src" / "tf" / "tf_error_catalogue.h"
out.write_bytes("\n".join(lines).encode("utf-8"))
print(f"{out.relative_to(root).as_posix()}: {len(cat['errors'])} errors, {len(raw)} bytes, sha256 {hashlib.sha256(raw).hexdigest()}")
